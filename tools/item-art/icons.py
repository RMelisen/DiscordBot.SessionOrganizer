# ---- Badges -------------------------------------------------------------------------------------
# A badge is a heater shield on a 22×22 canvas (one art pixel per screen pixel at Discord's 22 px):
# the outline, a two-pixel rim lit from the top left, and a two-tone field, whose colours say the
# tier (or moment / secret), with the subject on it. As with the trait tiles, only the subject is
# drawn by hand; shield() composes the rest. The tier also shows in the glints on the rim — one
# more per tier — rather than in extra borders. A 16×16 icon (a set's) fits as the subject as is.

# "L" lit rim, "S" shaded rim, "M" the rim's inner line, "f" field.
SHIELD = (
    "......................",
    "..##################..",
    ".#LLLLLLLLLLLLLLLLLL#.",
    ".#LMMMMMMMMMMMMMMMMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    ".#LMffffffffffffffMS#.",
    "..#LMffffffffffffMS#..",
    "...#LMffffffffffMS#...",
    "....#LMffffffffMS#....",
    ".....#LMMMMMMMMS#.....",
    "......##LLLSSS##......",
    "........######........",
    "......................",
)

# Where the glints go on the rim, in the order the tiers gain them.
SHIELD_GLINTS = ((5, 2), (2, 5), (11, 2), (2, 10))

SHIELD_TIERS = {
    # tier: (rim lit, rim shaded, rim's inner line, field, field shaded, glint colour, glint count)
    "bronze": ("J", "u", "j", "U", "u", "a", 0),
    "silver": ("s", "k", "G", "g", "k", "w", 1),
    "gold": ("y", "o", "A", "a", "o", "w", 2),
    "platinum": ("w", "G", "s", "h", "D", "x", 3),
    "diamond": ("x", "D", "B", "b", "d", "w", 4),
    "moment": ("I", "r", "i", "C", "c", "w", 2),
    "secret": ("b", "p", "P", "p", "q", "x", 1),
}


def shield(tier, *subject, at=None, glints=()):
    """A 22×22 badge: the SHIELD in the tier's colours and the subject ("." where the shield shows,
    at most 16×16) centred on it — or with its top left at `at`. The subject may cover the field
    and the rim's inner line, nothing further out. glints are (x, y, char), set last."""
    lit, shade, inner, field, field_shade, glint, count = SHIELD_TIERS[tier]
    rows = [r for r in subject if r.strip(".")]
    left = min(len(r) - len(r.lstrip(".")) for r in rows)
    width = max(len(r.rstrip(".")) for r in rows) - left
    rows = [r[left:left + width].ljust(width, ".") for r in rows]
    ox, oy = at or ((22 - width) // 2, 3 + (15 - len(rows)) // 2)
    grid = [[{"L": lit, "S": shade, "M": inner, "f": field if x + y <= 21 else field_shade}.get(c, c)
             for x, c in enumerate(r)] for y, r in enumerate(SHIELD)]
    for x, y in SHIELD_GLINTS[:count]:
        grid[y][x] = glint
    for sy, r in enumerate(rows):
        for sx, c in enumerate(r):
            if c == ".":
                continue
            x, y = ox + sx, oy + sy
            assert 0 <= y < 22 and 0 <= x < 22 and SHIELD[y][x] in "fM",                 f"the subject leaves the shield's face at ({x},{y})"
            grid[y][x] = c
    for x, y, c in glints:
        grid[y][x] = c
    return ["".join(r) for r in grid]



