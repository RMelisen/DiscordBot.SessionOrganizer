# ---- Traits -------------------------------------------------------------------------------------
# A Plynling trait is a tile, as in CK3: a framed square whose rim and background say the kind
# (enfance gold on wine, personnalité bronze on teal, coping silver on slate), with the symbol on it.
# Tiles are 22×22 like the badges — one art pixel per screen pixel at Discord's 22 px — so the
# symbol gets up to 16×16. Only the symbol is drawn by hand; tile() composes the frame.

TRAIT_KINDS = {
    # kind: (rim lit, rim shaded, rim's inner line, background, background shaded)
    "childhood": ("y", "o", "a", "r", "z"),
    "personality": ("J", "U", "j", "t", "T"),
    "coping": ("s", "g", "G", "P", "p"),
}


def outlined(*fill):
    """A symbol's fill (at most 8×8) wrapped in the 1-pixel outline: every empty cell touching the
    fill becomes "#". Holes of one or two cells come out dark, like a shadow."""
    w = max(len(r) for r in fill) + 2
    rows = ["." * w] + ["." + r.ljust(w - 2, ".") + "." for r in fill] + ["." * w]
    def filled(x, y):
        return 0 <= y < len(rows) and 0 <= x < w and rows[y][x] != "."
    return ["".join(c if c != "." or not any(filled(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                    else "#" for x, c in enumerate(r)) for y, r in enumerate(rows)]


def tile(kind, *symbol, at=None, glints=()):
    """A 22×22 trait tile: a 1-pixel outline with cut corners, a two-pixel rim, a two-tone
    background, and the symbol ("." where the background shows, at most 16×16) centred on it — or
    with its top left at `at`. The symbol may cover the rim's inner line, nothing further out.
    glints are (x, y, char), set last."""
    lit, shade, inner, bg, bg_shade = TRAIT_KINDS[kind]
    rows = [r for r in symbol if r.strip(".")]
    left = min(len(r) - len(r.lstrip(".")) for r in rows)
    width = max(len(r.rstrip(".")) for r in rows) - left
    rows = [r[left:left + width].ljust(width, ".") for r in rows]
    ox, oy = at or ((22 - width) // 2, (22 - len(rows)) // 2)
    grid = []
    for y in range(22):
        row = []
        for x in range(22):
            if not (1 <= x <= 20 and 1 <= y <= 20) or (x in (1, 20) and y in (1, 20)):
                row.append(".")
            elif x in (1, 20) or y in (1, 20) or (x in (2, 19) and y in (2, 19)):
                row.append("#")
            elif x in (2, 19) or y in (2, 19):
                row.append(lit if x == 2 or y == 2 else shade)
            elif x in (3, 18) or y in (3, 18):
                row.append(inner)
            else:
                row.append(bg if x + y <= 21 else bg_shade)
        grid.append(row)
    for sy, r in enumerate(rows):
        for sx, c in enumerate(r):
            if c == ".":
                continue
            x, y = ox + sx, oy + sy
            assert 3 <= x <= 18 and 3 <= y <= 18, f"the symbol leaves the tile's face at ({x},{y})"
            grid[y][x] = c
    for x, y, c in glints:
        grid[y][x] = c
    return ["".join(r) for r in grid]


