def recolour(key, mapping, glints=()):
    """Another icon's grid with its colours swapped (mapping: char → char) and a few pixels set:
    glints is (x, y, char)."""
    rows = [list(r) for r in ICONS[key].grid]
    rows = [[mapping.get(c, c) for c in r] for r in rows]
    for x, y, c in glints:
        rows[y][x] = c
    return ["".join(r) for r in rows]


